def select_rotating_edition(
    previous_editions_sent: int = 0,
    last_edition_id: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Deterministically rotates to the next editorial travel news edition so every
    subscription / re-send delivers visibly fresh, rotating news stories.
    """
    total = len(NEWSLETTER_EDITIONS)
    idx = max(0, previous_editions_sent) % total
    chosen = NEWSLETTER_EDITIONS[idx]

    # Guarantee the chosen edition differs from the previous edition sent to this subscriber
    if last_edition_id and chosen["edition_id"] == last_edition_id and total > 1:
        idx = (idx + 1) % total
        chosen = NEWSLETTER_EDITIONS[idx]

    return chosen


def get_israeli_dispatch_date() -> str:
    """Formats current UTC/local date as DD/MM/YYYY per AGENTS.md rule 5."""
    return datetime.now(timezone.utc).strftime("%d/%m/%Y")
